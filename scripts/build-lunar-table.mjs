/**
 * Builds src/data/lunar.ts from the Hong Kong Observatory's Gregorian-Lunar conversion tables (UTC+8, the same day as Singapore).
 * The Intl Chinese calendar was used before 22 Oct 2026 and is a day off for some new moons near midnight (it put Lunar New Year
 * 2027 on 7 Feb; HKO and Singapore's public holiday say 6 Feb), so HKO is the source.
 * Download https://www.hko.gov.hk/en/gts/time/calendar/text/files/T<year>e.txt for each year into one folder, then:
 *   node scripts/build-lunar-table.mjs --source <folder> --from 2026-10-01 --to 2031-12-31
 */
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { join } from 'node:path';

const arg = (k, d) => { const i = process.argv.indexOf('--' + k); return i > 0 ? process.argv[i + 1] : d; };
const source = arg('source'), from = arg('from', '2026-10-01'), to = arg('to', '2031-12-31');
if (!source) throw new Error('--source <folder of HKO T<year>e.txt files> is required');

const days = [], nine = [];
for (const file of readdirSync(source).filter(f => /^T\d{4}(e)?\.txt$/.test(f)).sort()) {
  let month = 0, ninth = false;
  for (const line of readFileSync(join(source, file), 'latin1').split(/\r?\n/)) {
    const m = /^(\d{4})\/(\d{1,2})\/(\d{1,2})\s+(\S.*?)\s{2,}/.exec(line);
    if (!m) continue;
    const day = `${m[1]}-${m[2].padStart(2, '0')}-${m[3].padStart(2, '0')}`, lunar = m[4].trim();
    const start = /^(\d+)(st|nd|rd|th) Lunar Month$/.exec(lunar);
    // A leap month repeats the previous month's name; only the first 9th month holds the Nine Emperor Gods festival.
    if (start) { month = Number(start[1]); ninth = month === 9 && !nine.some(d => d.startsWith(m[1])); }
    const date = start ? 1 : Number(lunar);
    if (!Number.isInteger(date) || date < 1 || date > 30) throw new Error(`${file}: cannot read "${lunar}" on ${day}`);
    if (day < from || day > to) continue;
    if (date === 1 || date === 15) days.push(`${day}:${date}`);
    if (ninth && month === 9 && date <= 9) nine.push(day);
  }
}
if (!days.length) throw new Error('No dates found in ' + source);
const version = createHash('sha256').update(JSON.stringify([days, nine])).digest('hex').slice(0, 12);
const rows = (list, per) => list.reduce((out, x, i) => (i % per ? out[out.length - 1].push(x) : out.push([x]), out), []).map(r => '  ' + r.map(x => JSON.stringify(x)).join(', ') + ',').join('\n');
writeFileSync(new URL('../src/data/lunar.ts', import.meta.url), `import { sgDay } from "../utils/sg-datetime";

/**
 * Lunar 1st/15th and Nine Emperor Gods days (Singapore dates, ${from} to ${to}), generated by scripts/build-lunar-table.mjs
 * from the Hong Kong Observatory's conversion tables on ${new Date().toISOString().slice(0, 10)}. Embedded because native Intl calendar support
 * varies and its Chinese calendar is a day off for some years. Leap months (5th in 2028, 3rd in 2031) keep their 1st and 15th.
 * Extend before ${to.slice(0, 4)}: the game's rules version includes LUNAR_VERSION, so the app and server agree on lunar days.
 */
const lunarDays: Record<string, 1 | 15> = Object.fromEntries(([
${rows(days, 8)}
] as const).map(entry => [entry.slice(0, 10), Number(entry.slice(11)) as 1 | 15]));
const nineEmperorGods = new Set([
${rows(nine, 9)}
]);
/** Changes whenever the table does; part of the game's rules version (src/game/sim/replay.ts). */
export const LUNAR_VERSION = "${version}";
export type LunarMoment = { day: string; label: string };
/** A plant-based observance today, if any; many people keep allium-free meals on these days. */
export function lunarMoment(now: number): LunarMoment | null {
  const day = sgDay(now);
  if (nineEmperorGods.has(day)) return { day, label: "Nine Emperor Gods" };
  const lunar = lunarDays[day];
  return lunar ? { day, label: lunar === 1 ? "Lunar 1st" : "Lunar 15th" } : null;
}
`);
console.log(`wrote ${days.length} lunar 1st/15th days and ${nine.length} Nine Emperor Gods days (${from} to ${to}), version ${version}`);
