"""Build the QT Cooker's v3 nutrition table (owner, 28 Oct 2026; docs/RECIPE_SOURCING_PLAN.md §5).

v3 = the v2 table (generated by scripts/recipe-nutrition.ts --bot; its last copy is kept in
scripts/nutrition/nutrition_sg.v2.json when v3 replaces it) plus, for every food:
- vitamins and minerals per 100 g (vitA ug RAE, vitC mg, vitE mg alpha-tocopherol, folate ug DFE, b12 ug, iron, calcium, zinc,
  magnesium, potassium mg) from USDA FoodData Central SR Legacy (public domain) by the food's fdcId;
- figures from the Taiwan FDA Food Nutrient Database (Open Government Data License v1.0) for USDA stand-ins and for foods
  USDA lacks (scripts/nutrition/bot-extras.json);
- the food's colour and staple grain (bot-extras.json).
Never edit the output by hand: change bot-extras.json or the app table and run this again.

Downloads (free, no account):
  USDA: https://fdc.nal.usda.gov/fdc-datasets/FoodData_Central_sr_legacy_food_csv_2018-04.zip (unzip)
  Taiwan FDA: https://data.fda.gov.tw/data/opendata/export/20/csv (a zip holding 20_2.csv)
Run: python -I scripts/nutrition/build_bot_v3.py <usda folder> <taiwan 20_2.csv> <repository root>
"""
import csv
import datetime as dt
import json
import re
import sys
from pathlib import Path

MICRO = ('vitA', 'vitC', 'vitE', 'folate', 'b12', 'iron', 'calcium', 'zinc', 'magnesium', 'potassium')
USDA_IDS = {'1106': 'vitA', '1162': 'vitC', '1109': 'vitE', '1190': 'folate', '1178': 'b12', '1089': 'iron', '1087': 'calcium',
            '1095': 'zinc', '1090': 'magnesium', '1092': 'potassium'}
USDA_FOLATE_TOTAL = '1177'  # used when SR Legacy gives no folate DFE (unfortified foods: the same value)
TW_ITEMS = {'熱量': 'kcal', '粗蛋白': 'protein', '粗脂肪': 'fat', '總碳水化合物': 'carbs', '膳食纖維': 'fibre', '糖質總量': 'sugar',
            '鈉': 'sodium', '維生素C': 'vitC', 'α-生育酚': 'vitE', '葉酸': 'folate', '維生素B12': 'b12', '鐵': 'iron', '鈣': 'calcium',
            '鋅': 'zinc', '鎂': 'magnesium', '鉀': 'potassium', '視網醇': 'retinol', 'β-胡蘿蔔素': 'betaCarotene', 'α-胡蘿蔔素': 'alphaCarotene'}
COLOURS = {'green', 'red', 'yellow', 'black', 'white'}
STAPLES = {'rice', 'wheat', 'soybean', 'corn', 'tuber'}


def number(text):
    try:
        return float(str(text).strip())
    except ValueError:
        return None


def usda_micro(folder, ids):
    """fdcId -> {micro field: per 100 g} for the given foods."""
    wanted = {str(i) for i in ids}
    found, folate_total = {}, {}
    with open(Path(folder) / 'food_nutrient.csv', encoding='utf-8', newline='') as handle:
        for row in csv.DictReader(handle):
            fdc, nutrient = row['fdc_id'], row['nutrient_id']
            if fdc not in wanted:
                continue
            value = number(row['amount'])
            if nutrient in USDA_IDS and value is not None:
                found.setdefault(fdc, {})[USDA_IDS[nutrient]] = value
            elif nutrient == USDA_FOLATE_TOTAL and value is not None:
                folate_total[fdc] = value
    for fdc, value in folate_total.items():
        found.setdefault(fdc, {}).setdefault('folate', value)
    return found


def taiwan_foods(path, ids):
    """Taiwan id -> {name, per100g (macros and micros)}; vitamin A as RAE from retinol and carotenes."""
    rows = {}
    with open(path, encoding='utf-8-sig', newline='') as handle:
        for row in csv.DictReader(handle):
            food = row['整合編號']
            if food not in ids or row['分析項'] not in TW_ITEMS:
                continue
            entry = rows.setdefault(food, {'name': row['樣品名稱'], 'english': row['樣品英文名稱'].strip(), 'values': {}})
            value = number(row['每100克含量'])
            if value is not None:
                entry['values'][TW_ITEMS[row['分析項']]] = value
    for entry in rows.values():
        v = entry.pop('values')
        carotenes = [v.get('retinol'), v.get('betaCarotene'), v.get('alphaCarotene')]
        if any(x is not None for x in carotenes):
            v['vitA'] = round((v.get('retinol') or 0) + (v.get('betaCarotene') or 0) / 12 + (v.get('alphaCarotene') or 0) / 24, 2)
        entry['per100g'] = {k: v[k] for k in ('kcal', 'protein', 'fat', 'carbs', 'fibre', 'sugar', 'sodium', *MICRO) if k in v}
    missing = set(ids) - set(rows)
    if missing:
        raise SystemExit('Taiwan FDA ids not found: ' + ', '.join(sorted(missing)))
    return rows


def validate(extras, foods):
    for key, colour in extras['colour'].items():
        if key not in foods or colour not in COLOURS:
            raise SystemExit(f'bad colour entry {key}={colour}')
    for key, staple in extras['staple'].items():
        if key not in foods or staple not in STAPLES:
            raise SystemExit(f'bad staple entry {key}={staple}')
    for key in [*extras['taiwan'], *extras['noMicro']]:
        if key not in foods:
            raise SystemExit(f'unknown food {key}')
    for key, food in extras['newFoods'].items():
        if key in foods or food.get('colour', 'white') not in COLOURS or food.get('staple', 'rice') not in STAPLES:
            raise SystemExit(f'bad new food {key}')
        for pattern in food['match']:
            re.compile(pattern)
    for key, label in extras.get('labels', {}).items():
        if (label.get('base') and label['base'] not in foods) or (not label.get('base') and key not in foods):
            raise SystemExit(f'bad label {key}: unknown base or food')
        if set(label.get('per100g') or {}) - {'kcal', 'protein', 'fat', 'carbs', 'fibre', 'sugar', 'sodium'}:
            raise SystemExit(f'bad label {key}: per100g takes the seven main figures only')
        for pattern in label.get('match', []):
            re.compile(pattern)


def build(usda_folder, taiwan_csv, repo):
    repo = Path(repo)
    v2 = json.loads((repo / 'ops/qt-team/nutrition_sg.json').read_text(encoding='utf-8'))
    if v2.get('version') == 3:
        v2 = json.loads((repo / 'scripts/nutrition/nutrition_sg.v2.json').read_text(encoding='utf-8'))
    if v2.get('version') != 2:
        raise SystemExit('expected the v2 table (scripts/recipe-nutrition.ts --bot)')
    extras = json.loads((repo / 'scripts/nutrition/bot-extras.json').read_text(encoding='utf-8'))
    foods = {k: dict(v) for k, v in v2['foods'].items()}
    validate(extras, foods)
    micro = usda_micro(usda_folder, [f['fdcId'] for f in foods.values() if f.get('fdcId')]
                       + [l['fdcId'] for l in extras.get('labels', {}).values() if l.get('fdcId')])
    tw = taiwan_foods(taiwan_csv, set(extras['taiwan'].values()) | {f['taiwan'] for f in extras['newFoods'].values()})
    claimed = {p for f in [*extras['newFoods'].values(), *extras.get('labels', {}).values()] for p in f.get('match', [])}
    for key, food in foods.items():
        food['match'] = [p for p in food.get('match', []) if p not in claimed]
        if key in extras['taiwan']:
            source = tw[extras['taiwan'][key]]
            for stale in ('fdcId', 'usda', 'analogue'):
                food.pop(stale, None)
            food['per100g'] = source['per100g']
            food['source'] = {'dataset': 'Taiwan FDA', 'id': extras['taiwan'][key], 'name': source['name']}
            food['name'] = extras.get('names', {}).get(key, food['name'])
        elif food.get('per100g') and food.get('fdcId') and key not in extras['noMicro']:
            food['per100g'] = {**food['per100g'], **micro.get(str(food['fdcId']), {})}
        if key in extras['colour']:
            food['colour'] = extras['colour'][key]
        if key in extras['staple']:
            food['staple'] = extras['staple'][key]
    for key, patch in extras.get('patch', {}).items():  # extra aliases and unit weights for v2 foods
        foods[key]['match'] = foods[key].get('match', []) + patch.get('match', [])
        foods[key].update({k: v for k, v in patch.items() if k != 'match'})
    for key, spec in extras.get('negligible', {}).items():  # eaten in trace amounts or not at all: matched, no nutrients
        foods[key] = {'name': spec['name'], 'negligible': True, 'match': spec['match']}
    for key, spec in extras['newFoods'].items():
        source = tw[spec['taiwan']]
        food = {k: spec[k] for k in ('name', 'each', 'gPerMl', 'colour', 'staple') if k in spec}
        food.update(match=spec['match'], per100g=source['per100g'], source={'dataset': 'Taiwan FDA', 'id': spec['taiwan'], 'name': source['name']})
        foods[key] = food
    for key, spec in extras.get('labels', {}).items():
        # Open product labels (owner, 31 Oct 2026: the ricotta stand-in halved paneer's protein; tau kwa used a softer tofu).
        # A new food starts as a copy of its base food (vitamins, minerals, colour, staple); the label's main figures replace
        # the base's, and micro: false drops vitamins and minerals the stand-in would misstate.
        food = dict(foods[spec['base']]) if spec.get('base') else foods[key]
        food = {k: v for k, v in food.items() if k not in ('fdcId', 'usda', 'legacy')} if spec.get('base') or spec.get('per100g') else food
        per = dict(food.get('per100g') or {})
        if spec.get('micro') is False:
            per = {k: v for k, v in per.items() if k not in MICRO}
        if spec.get('fdcId'):  # a USDA food of its own: its vitamins and minerals, not the base food's
            per = {**{k: v for k, v in per.items() if k not in MICRO}, **micro.get(str(spec['fdcId']), {})}
        per.update(spec.get('per100g') or {})
        food.update({k: spec[k] for k in ('name', 'each', 'match') if k in spec}, per100g=per)
        if spec.get('source'):
            food['source'] = spec['source']
        foods[key] = food
    return {'version': 3, 'built': dt.date.today().isoformat(), 'table': v2['table'],
            'source': v2['source'] + ' Vitamins and minerals: USDA SR Legacy (public domain). Foods marked with source: Taiwan FDA Food '
                      'Nutrient Database (Open Government Data License v1.0). Built by scripts/nutrition/build_bot_v3.py from '
                      'scripts/nutrition/bot-extras.json.',
            'micro': list(MICRO), 'units': v2['units'], 'foods': foods}


def main():
    if len(sys.argv) != 4:
        raise SystemExit(__doc__)
    usda, taiwan, repo = sys.argv[1:]
    repo_path = Path(repo)
    current = repo_path / 'ops/qt-team/nutrition_sg.json'
    if json.loads(current.read_text(encoding='utf-8')).get('version') == 2:
        (repo_path / 'scripts/nutrition/nutrition_sg.v2.json').write_text(current.read_text(encoding='utf-8'), encoding='utf-8')
    table = build(usda, taiwan, repo)
    current.write_text(json.dumps(table, ensure_ascii=False, indent=1) + '\n', encoding='utf-8')
    with_micro = sum(1 for f in table['foods'].values() if any(k in (f.get('per100g') or {}) for k in MICRO))
    print(f"v3 table: {len(table['foods'])} foods, {with_micro} with vitamins/minerals, "
          f"{sum('colour' in f for f in table['foods'].values())} with a colour, {sum('staple' in f for f in table['foods'].values())} with a staple")


if __name__ == '__main__':
    main()
