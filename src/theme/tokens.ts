export function themeFor(palette: Palette, dark: boolean) {
  const f = families[palette];
  const surface = dark ? f.darkSurface : f.surface;
  const monochrome = palette === "monochrome";
  const foreground = monochrome ? (dark ? "#f5f5f5" : "#1c1c1c") : dark ? "#fcfaf8" : "#232825";
  return {
    dark,
    background: dark ? f.dark[0] : f.light[0],
    gradient: dark ? f.dark : f.light,
    backdrop: dark ? f.dark : f.backdrop,
    foreground,
    mutedForeground: surface.mutedForeground,
    card: surface.card,
    border: surface.border,
    frameBorder: dark ? surface.border : "#ffffff",
    divider: surface.divider,
    muted: surface.muted,
    accent: dark ? f.accentDark : f.accent,
    accentSoft: dark ? surface.muted : f.soft,
    action: monochrome && dark ? ["#f5f5f5", "#f5f5f5"] as const : f.action,
    actionForeground: monochrome && dark ? "#000000" : "#ffffff",
    providerForeground: dark ? "#ffffff" : "#1f1f1f",
    shadow: monochrome ? "#000000" : dark ? "#110d19" : f.surface.shadow,
    success: dark ? "#a9e5c7" : "#276049",
    successSoft: dark ? "#233c33" : "#eef6ef",
    warning: dark ? "#ffe3a8" : "#875509",
    warningSoft: dark ? "#403525" : "#fff4de",
    error: dark ? "#ffc5bd" : "#a82b35",
    overlay: monochrome ? "rgba(0,0,0,0.58)" : "rgba(24,15,28,0.58)",
    transparent: "transparent",
    mediaSurface: monochrome ? "#111111" : "#171d19",
    mediaForeground: "#ffffff",
    mediaMutedForeground: monochrome ? "#e5e5e5" : "#eee9df",
    mediaProviderForeground: "#ffffff",
    mediaControl: monochrome ? "rgba(0,0,0,0.84)" : "rgba(23,29,25,0.84)",
    mediaRating: "#ffd16a",
    /** Lotus tier colours (Lotus Avatar): the same in every palette and mode, like a status colour. */
    lotus: { pink: "#f59cc3", purple: "#b18ae8", blue: "#6fc0f2", golden: "#f6c453", petal: "#ffe3ee", ray: "rgba(255,247,226,0.85)",
      frost: dark ? "rgba(48,39,52,0.55)" : "rgba(255,255,255,0.55)" },
    // Mochi Chef mascot colours: cheek blush, and the brown of its face for the "Quin" of the wordmark. The same in every palette.
    mascot: { blush: "#f4907a", ink: "#52271a" },
    // Artwork keeps its own brand colours; the form chrome can follow the neutral palette.
    welcome: {
      background: monochrome ? (dark ? f.dark[0] : "#ffffff") : dark ? f.dark[0] : "#fffcf9",
      foreground: monochrome ? foreground : dark ? "#fcfaf8" : "#070b10",
      mutedForeground: monochrome ? surface.mutedForeground : dark ? surface.mutedForeground : "#735d59",
      accent: monochrome ? (dark ? f.accentDark : f.accent) : dark ? f.accentDark : "#c52f23",
      primary: monochrome ? (dark ? f.accentDark : f.accent) : dark ? f.accentDark : "#b9392c",
      border: monochrome ? surface.border : dark ? surface.border : "#bfc1ca",
      dot: monochrome ? surface.border : dark ? surface.border : "#d2cac5",
    },
    // Game scene effects (falling vine leaves, the companion's heart, window sunlight): part of the painted café, the same in every palette.
    scene: { leaf: "#86b94f", leafDeep: "#5f8f3a", heart: "#ff7aa2", sun: "rgba(255,222,150,0.9)", sunSoft: "rgba(255,222,150,0)" },
    mediaDivider: "rgba(255,255,255,0.28)",
    photoBlend: monochrome ? ["rgba(0,0,0,0)", "rgba(0,0,0,0.58)", "rgba(0,0,0,0.76)"] as const
      : ["rgba(23,29,25,0)", "rgba(23,29,25,0.58)", "rgba(23,29,25,0.76)"] as const,
    navigation: {
      ...f.navigation,
      glassTint: dark ? f.navigation.glassDark : f.navigation.glassLight,
      foreground,
      selectedForeground: dark ? f.accentDark : f.accent,
      border: dark ? "rgba(252,250,248,0.28)" : "rgba(255,255,255,0.52)",
      selection: dark ? f.accentDark + "38" : f.soft + "c4",
      hover: dark ? f.accentDark + "15" : f.soft + "88",
      selectionBorder: dark ? f.accentDark + "65" : f.accent + "44",
      selectionGlow: dark ? f.accentDark + "42" : "rgba(255,255,255,0.84)",
    },
    swatches: families,
  };
}
